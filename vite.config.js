// Настройки Vite (локального сервера для разработки).
import { defineConfig } from 'vite';

export default defineConfig({
  // Относительные пути в собранной версии — чтобы её можно было выложить в любую папку сайта.
  base: './',
  server: {
    // Сервер виден в домашней сети: телефон в том же Wi-Fi откроет игру
    // по адресу компьютера (его Vite пишет в терминале как "Network: http://192.168...").
    host: true,
    watch: {
      // Сервер сам раз в 300 мс проверяет, изменились ли файлы.
      // Без этого Windows иногда "забывает" сообщить об изменениях
      // (похоже, из-за кириллицы в пути к папке), и страница не обновляется.
      usePolling: true,
      interval: 300,
    },
  },
});
